function QualityMeter({ score }: { score: number }) {
  const pct = Math.min(Math.max(score, 0), 10) * 10;
  const color =
    score >= 7
      ? 'bg-emerald-500'
      : score >= 4
        ? 'bg-amber-500'
        : 'bg-red-500';

  return (
    <div className="space-y-1.5">
      <div className="flex items-baseline justify-between">
        <span className="text-sm font-medium text-zinc-700 dark:text-zinc-300">
          Drafting Quality
        </span>
        <span className="text-lg font-bold text-zinc-900 dark:text-zinc-100">
          {score}
          <span className="text-sm font-normal text-zinc-400">/10</span>
        </span>
      </div>
      <div className="h-2 w-full overflow-hidden rounded-full bg-zinc-200 dark:bg-zinc-700">
        <div
          className={`h-full rounded-full transition-all duration-500 ${color}`}
          style={{ width: `${pct}%` }}
        />
      </div>
    </div>
  );
}

function resultToMarkdown(r: ReviewResult): string {
  const lines: string[] = [];
  if (r.isDemo) {
    lines.push('> NOTE: DEMO MODE — Illustrative sample results. Not generated by a live AI model.\n');
  }
  lines.push('# Contract Review Results\n');
  lines.push(`**Overall Risk Level:** ${r.overallRiskLevel.toUpperCase()}\n`);
  lines.push(`**Drafting Quality:** ${r.draftingQualityScore}/10\n`);
  if (r.draftingQualityBreakdown) {
    lines.push(
      `**Dimension scores:** Clarity ${r.draftingQualityBreakdown.clarity}/10; Completeness ${r.draftingQualityBreakdown.completeness}/10; Consistency ${r.draftingQualityBreakdown.consistency}/10; Risk allocation ${r.draftingQualityBreakdown.riskAllocation}/10; Operational precision ${r.draftingQualityBreakdown.operationalPrecision}/10; Dispute resolution ${r.draftingQualityBreakdown.disputeResolution}/10; Drafting structure ${r.draftingQualityBreakdown.draftingStructure}/10.\n`,
    );
  }
  const findings = summarizeReviewFindings(r);
  lines.push(
    `**Evidence-supported existing clauses:** ${findings.analyzedClauseCount}; **risky clauses:** ${findings.riskyClauseCount}; **insufficiently supported observations:** ${findings.insufficientEvidenceCount}; **missing provisions:** ${findings.missingClauseCount}; **ambiguous provisions:** ${findings.ambiguousProvisionCount}\n`,
  );
  if (r.documentInfo) {
    lines.push(
      `**Document:** ${r.documentInfo.format.toUpperCase()} · ${r.documentInfo.characterCount.toLocaleString()} characters · ${r.documentInfo.pageCount ?? 'Page count unavailable'} pages\n`,
    );
  }
  lines.push('## Executive Summary\n');
  lines.push(r.executiveSummary + '\n');

  if (r.contractStrengths?.length) {
    lines.push('## Contract Strengths\n');
    r.contractStrengths.forEach((strength) => lines.push(`- ${strength}`));
    lines.push('');
  }

  if (r.missingClauses?.length) {
    lines.push('## Missing Provisions (not identified in extracted document)\n');
    r.missingClauses.forEach((clause) => {
      lines.push(`### ${clause.clauseTitle} (${clause.riskLevel.toUpperCase()})`);
      lines.push(`**Why it matters:** ${clause.whyItMatters}`);
      lines.push(`**Potential consequences:** ${clause.potentialConsequences}`);
      lines.push(`**Recommended action:** ${clause.recommendedAction}\n`);
      lines.push(`**Suggested wording:** ${clause.proposedWording}\n`);
      if (clause.evidenceLimitations) {
        lines.push(`**Evidence limitations:** ${clause.evidenceLimitations}\n`);
      }
      clause.legalReferences.forEach((reference) => {
        lines.push(
          `**General legal reference (unverified):** ${reference.actName}, section ${reference.section} — ${reference.relevance} (not checked against current official law)\n`,
        );
      });
    });
  }

  if (r.ambiguousProvisions?.length) {
    lines.push('## Ambiguous Provisions\n');
    r.ambiguousProvisions.forEach((provision) => {
      lines.push(`### ${provision.clauseTitle} (${provision.riskLevel.toUpperCase()})`);
      lines.push(`**Original:** ${provision.originalText}`);
      lines.push(`**Ambiguity:** ${provision.ambiguity}`);
      lines.push(`**Possible interpretations:** ${provision.possibleInterpretations.join('; ')}\n`);
    });
  }

  if (r.draftingQualityNotes) {
    lines.push('## Drafting Quality Notes\n');
    lines.push(r.draftingQualityNotes + '\n');
  }

  if (r.recommendations.length) {
    lines.push('## Recommendations\n');
    r.recommendations.forEach((rec, i) => lines.push(`${i + 1}. ${rec}`));
    lines.push('');
  }

  if (findings.clauses.length) {
    lines.push('## Clause Analysis\n');
    findings.clauses.forEach((c) => {
      lines.push(`### ${c.clauseTitle} (${c.riskLevel.toUpperCase()} risk)\n`);
      if (c.originalText) {
        lines.push(`**Original:** ${c.originalText}\n`);
      } else {
        lines.push('**Evidence status:** Insufficiently supported; no exact quotation was matched.\n');
      }
      lines.push(`**Issue:** ${c.issue}\n`);
      if (c.ambiguity) {
        lines.push(`**Ambiguity:** ${c.ambiguity}\n`);
        if (c.possibleInterpretations?.length) {
          lines.push(
            `**Possible interpretations:** ${c.possibleInterpretations.join('; ')}\n`,
          );
        }
      }
      lines.push(`**Why it matters:** ${c.whyItMatters || ''}\n`);
      lines.push(`**Potential consequences:** ${c.potentialConsequences || ''}\n`);
      lines.push(`**Recommended action:** ${c.recommendedAction || ''}\n`);
      lines.push(`**Proposed Revision:** ${c.proposedRevision}\n`);
      lines.push(`**Reasoning:** ${c.reasoning}\n`);
      if (c.evidenceLimitations) {
        lines.push(`**Evidence limitations:** ${c.evidenceLimitations}\n`);
      }
      if (c.legalReferences?.length) {
        c.legalReferences.forEach((reference) => {
          lines.push(
            `**General legal reference (unverified):** ${reference.actName}, section ${reference.section} — ${reference.relevance} (not checked against current official law)\n`,
          );
        });
      }
    });
  }

  if (r.legalReferences?.length) {
    lines.push('## Legal References\n');
    r.legalReferences.forEach((reference) => {
      lines.push(
        `- General reference only (unverified): ${reference.actName}, section ${reference.section}: ${reference.relevance}. Current official law was not checked.`,
      );
    });
    lines.push('');
  }

  if (r.limitations?.length) {
    lines.push('## Limitations\n');
    r.limitations.forEach((limitation) => lines.push(`- ${limitation}`));
  }

  return lines.join('\n');
}

function RiskDistribution({
  summary,
}: {
  summary: ReviewFindingsSummary;
}) {
  const counts = {
    high: summary.highRisk,
    medium: summary.mediumRisk,
    low: summary.lowRisk,
  };
  const total = summary.analyzedClauseCount;
  const risks = [
    { key: 'high', label: 'High', color: 'bg-red-500', count: counts.high },
    { key: 'medium', label: 'Medium', color: 'bg-amber-500', count: counts.medium },
    { key: 'low', label: 'Low', color: 'bg-emerald-500', count: counts.low },
  ];

  return (
    <section className="rounded-xl border border-zinc-200 bg-white p-6 shadow-sm dark:border-zinc-700 dark:bg-zinc-900">
      <h3 className="text-sm font-semibold text-zinc-800 dark:text-zinc-200">
        Risk distribution
      </h3>
      <p className="mt-1 text-xs text-zinc-500 dark:text-zinc-400">
        Based on {total} unique, evidence-supported existing clause
        {total === 1 ? '' : 's'}. Missing provisions and ambiguous provisions
        are separate categories; insufficiently supported observations are not
        counted.
      </p>
      <div className="mt-4 flex h-2 overflow-hidden rounded-full bg-zinc-100 dark:bg-zinc-800">
        {risks.map((risk) => (
          <div
            key={risk.key}
            className={risk.color}
            style={{ width: total ? `${(risk.count / total) * 100}%` : '0%' }}
          />
        ))}
      </div>
      <div className="mt-4 grid grid-cols-3 gap-3">
        {risks.map((risk) => (
          <div key={risk.key} className="flex items-center gap-2 text-xs">
            <span className={`h-2 w-2 rounded-full ${risk.color}`} />
            <span className="text-zinc-600 dark:text-zinc-400">
              {risk.label}
            </span>
            <span className="ml-auto font-semibold text-zinc-800 dark:text-zinc-200">
              {risk.count}
            </span>
          </div>
        ))}
      </div>
      <p className="mt-4 border-t border-zinc-100 pt-3 text-xs leading-relaxed text-zinc-500 dark:border-zinc-800 dark:text-zinc-400">
        {summary.riskyClauseCount} risky existing clause
        {summary.riskyClauseCount === 1 ? '' : 's'} ·{' '}
        {summary.missingClauseCount} missing provision
        {summary.missingClauseCount === 1 ? '' : 's'} ·{' '}
        {summary.ambiguousProvisionCount} evidence-supported ambiguous
        provision{summary.ambiguousProvisionCount === 1 ? '' : 's'} ·{' '}
        {summary.insufficientEvidenceCount} insufficiently supported
        observation{summary.insufficientEvidenceCount === 1 ? '' : 's'}
      </p>
    </section>
  );
}

